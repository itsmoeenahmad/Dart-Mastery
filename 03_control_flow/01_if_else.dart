/*
if, else if, and else choose which block of code runs when conditions are evaluated.
*/

void main() {
  //If Statement

  int num = 99;

  if (num == 100) {
    print('num is 100');
  }
  // Use if-else when one of two branches should run.

  //If-Else Statement

  int a = 12;
  int b = 13;

  if (a > b) {
    print('a is greater than b');
  } else {
    print('b is greater than a');
  }
}
