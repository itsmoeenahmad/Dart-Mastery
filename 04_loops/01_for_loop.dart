/*
A for loop repeats code while controlling initialization, condition checking, and update in one statement.
*/

void main() {
  //For Loop

  //Syntax:

  // for(initialization, condition, increment/decrement)
  //   {
  //     //body
  //   }

  for (int i = 0; i < 10; i++) {
    print('hello');
  }
}
